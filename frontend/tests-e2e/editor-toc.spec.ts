import { test, expect, type Page } from '@playwright/test'

test.use({ actionTimeout: 8000 })
const paragraphs = (count: number) => '<p>这一段用于检查长文滚动与目录定位。</p>'.repeat(count)
const content = '<h1>开始写作</h1><p>第一段内容。</p><h2>准备工作</h2>' + paragraphs(18) + '<h3>具体步骤</h3>' + paragraphs(18) + '<h2>完成检查</h2>' + paragraphs(24)

async function open(page: Page, html = content, expectedHeadings = 4) {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    localStorage.setItem('userId', '7')
    localStorage.setItem('token', `qa.${btoa(JSON.stringify({ sub: '7', exp: Date.now() / 1000 + 3600 }))}.toc`)
  })
  await page.route('**/api/**', route => {
    const path = new URL(route.request().url()).pathname
    let data: any = []
    if (path.endsWith('/article/42/edit')) data = { articleId: '42', title: '写作中的文章', content: html, status: 0, revisionId: 'r1', lockVersion: 1 }
    if (path.endsWith('/user/space/7')) data = { role: 0, status: 1 }
    return route.fulfill({ json: { code: 200, data } })
  })
  await page.goto('/edit-article?id=42')
  const editor = page.locator('[data-slate-editor]'), toc = page.getByRole('navigation', { name: '正文目录' })
  await expect(editor).toContainText('第一段内容。')
  await expect(toc.locator('.toc-entry')).toHaveCount(expectedHeadings)
  return { editor, toc, errors }
}

for (const fullscreen of [false, true]) test(`compact margins and live left directory in ${fullscreen ? 'fullscreen' : 'ordinary editor'}`, async ({ page }, info) => {
  await page.setViewportSize({ width: 2540, height: 1000 })
  const { editor, toc, errors } = await open(page)
  const editorId = await editor.getAttribute('id')
  if (fullscreen) await page.locator('.toolbar [data-menu-key="fullScreen"]').click()
  const firstHeading = editor.locator('h1'), before = await firstHeading.boundingBox(), directory = await toc.boundingBox()
  if (fullscreen) expect(before!.x - directory!.x - directory!.width).toBeLessThan(80)
  else expect(before!.x).toBeLessThan(280)
  expect(before!.width).toBeGreaterThan(1600)
  expect(directory!.x).toBeGreaterThanOrEqual(0)
  expect(directory!.x + directory!.width).toBeLessThan(before!.x)
  await expect(toc.locator('.toc-toggle')).toBeHidden()
  await expect(toc.getByRole('button', { name: '准备工作', exact: true })).toBeVisible()
  const headingPadding = await toc.locator('.toc-entry').evaluateAll(elements => elements.map(el => parseFloat(getComputedStyle(el).paddingLeft)))
  expect(headingPadding).toEqual([10, 22, 34, 22])
  const backgroundScroll = await page.evaluate(() => window.scrollY)
  await toc.getByRole('button', { name: '完成检查', exact: true }).click()
  const target = editor.getByRole('heading', { name: '完成检查', exact: true })
  await expect(target).toBeInViewport()
  const toolbar = await page.locator('.article-rich-editor .toolbar').boundingBox(), targetBox = await target.boundingBox()
  expect(targetBox!.y).toBeGreaterThanOrEqual(toolbar!.y + toolbar!.height)
  expect(targetBox!.y).toBeLessThan(toolbar!.y + toolbar!.height + 70)
  await expect(toc.getByRole('button', { name: '完成检查', exact: true })).toHaveAttribute('aria-current', 'location')
  await expect(toc.getByRole('button', { name: '开始写作', exact: true })).toBeInViewport()
  if (fullscreen) expect(await page.evaluate(() => window.scrollY)).toBe(backgroundScroll)
  await expect(editor).toHaveAttribute('id', editorId!)
  await page.screenshot({ path: info.outputPath(`editor-directory-${fullscreen ? 'fullscreen' : 'ordinary'}.png`), animations: 'disabled' })
  expect(errors).toEqual([])
})

test('fullscreen separates the directory from the writing surface and each scrolls independently', async ({ page }, info) => {
  await page.setViewportSize({ width: 1920, height: 1000 })
  const chapters = '<p>第一段内容。</p>' + Array.from({ length: 60 }, (_, index) => `<h2>章节 ${index + 1}</h2>${paragraphs(5)}`).join('') + paragraphs(20)
  const { editor, toc, errors } = await open(page, chapters, 60)
  await page.locator('.toolbar [data-menu-key="fullScreen"]').click()
  const fullscreen = page.getByRole('dialog', { name: '全屏编辑正文', exact: true })
  const bounds = (await toc.boundingBox())!, header = (await fullscreen.locator('.fullscreen-bar').boundingBox())!
  const toolbar = (await fullscreen.locator('.toolbar').boundingBox())!, writing = (await fullscreen.locator(':scope > .editor').boundingBox())!
  expect(bounds.x).toBe(0)
  expect(bounds.y).toBeCloseTo(header.y + header.height, 0)
  expect(bounds.y + bounds.height).toBe(1000)
  expect(bounds.x + bounds.width).toBeCloseTo(toolbar.x, 0)
  expect(bounds.x + bounds.width).toBeCloseTo(writing.x, 0)
  expect(writing.y).toBeCloseTo(toolbar.y + toolbar.height, 0)
  expect(await toc.evaluate(el => parseFloat(getComputedStyle(el).borderRightWidth))).toBeGreaterThan(0)
  expect(await toc.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(await fullscreen.locator(':scope > .editor').evaluate(el => getComputedStyle(el).backgroundColor))
  const list = toc.locator('.toc-entries'), scroll = fullscreen.locator('.w-e-scroll')
  const pageScroll = await page.evaluate(() => window.scrollY)
  await list.hover(); await page.mouse.wheel(0, 500)
  await expect.poll(() => list.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(0)
  await editor.locator('p').first().hover(); await page.mouse.wheel(0, 500)
  await expect.poll(() => scroll.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect(await toc.boundingBox()).toEqual(bounds)
  expect(await page.evaluate(() => window.scrollY)).toBe(pageScroll)
  await toc.getByRole('button', { name: '章节 60', exact: true }).click()
  await expect(editor.getByRole('heading', { name: '章节 60', exact: true })).toBeInViewport()
  await expect(toc.getByRole('button', { name: '章节 60', exact: true })).toHaveAttribute('aria-current', 'location')
  await page.screenshot({ path: info.outputPath('fullscreen-separated-directory.png'), animations: 'disabled' })
  expect(errors).toEqual([])
})

test('fullscreen gives an empty directory less space and grows/shrinks it as headings change', async ({ page }, info) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  const { editor, toc, errors } = await open(page, '<p>第一段内容。</p><p></p>', 0)
  const editorId = await editor.getAttribute('id')
  await page.locator('.toolbar [data-menu-key="fullScreen"]').click()
  const fullscreen = page.getByRole('dialog', { name: '全屏编辑正文', exact: true }), surface = fullscreen.locator(':scope > .editor')
  await expect(toc.locator('.toc-empty-short')).toBeVisible()
  const emptyWidth = (await toc.boundingBox())!.width, emptySurfaceWidth = (await surface.boundingBox())!.width
  expect(emptyWidth).toBeLessThanOrEqual(90)
  expect((await surface.boundingBox())!.x).toBeCloseTo(emptyWidth, 0)
  await page.screenshot({ path: info.outputPath('fullscreen-empty-directory.png'), animations: 'disabled' })
  await editor.locator('p').last().click(); await page.keyboard.type('/h2'); await page.keyboard.press('Enter'); await page.keyboard.type('新增标题')
  await expect(toc.getByRole('button', { name: '新增标题', exact: true })).toBeVisible()
  const expandedWidth = (await toc.boundingBox())!.width, expandedSurfaceWidth = (await surface.boundingBox())!.width
  expect(expandedWidth).toBeGreaterThan(emptyWidth + 100)
  expect(emptySurfaceWidth - expandedSurfaceWidth).toBeCloseTo(expandedWidth - emptyWidth, 0)
  await editor.locator('h2').hover()
  await page.getByRole('button', { name: '段落格式：二级标题', exact: true }).click()
  await page.getByRole('menuitemradio', { name: '正文', exact: true }).click()
  await expect(toc.locator('.toc-entry')).toHaveCount(0)
  await expect.poll(async () => (await toc.boundingBox())!.width).toBe(emptyWidth)
  await expect(editor.locator('p').last()).toHaveText('新增标题')
  await page.keyboard.press('Control+z')
  await expect(toc.getByRole('button', { name: '新增标题', exact: true })).toBeVisible()
  await expect.poll(async () => (await toc.boundingBox())!.width).toBe(expandedWidth)
  await expect(editor).toHaveAttribute('id', editorId!)
  await page.screenshot({ path: info.outputPath('fullscreen-heading-directory.png'), animations: 'disabled' })
  expect(errors).toEqual([])
})

test('directory follows heading typing, conversion, deletion and undo without adding content markup', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  const { editor, toc, errors } = await open(page, '<h1>开始写作</h1><p>第一段内容。</p><h2>准备工作</h2><h3>具体步骤</h3><h2>完成检查</h2><p></p>')
  await editor.locator('h2').first().click()
  await page.keyboard.press('End'); await page.keyboard.type('更新')
  await expect(toc.getByRole('button', { name: '准备工作更新', exact: true })).toBeVisible()
  await editor.locator('p').last().click(); await page.keyboard.type('/h2'); await page.keyboard.press('Enter'); await page.keyboard.type('新增章节')
  await expect(toc.locator('.toc-entry')).toHaveCount(5)
  await expect(toc.getByRole('button', { name: '新增章节', exact: true })).toBeVisible()
  await page.keyboard.press('Home'); await page.keyboard.press('Shift+End'); await page.keyboard.press('Backspace')
  await expect(toc.getByRole('button', { name: '未命名标题', exact: true })).toBeVisible()
  await page.keyboard.press('Backspace')
  await expect(toc.locator('.toc-entry')).toHaveCount(4)
  await page.keyboard.press('Control+z')
  await expect(toc.locator('.toc-entry')).toHaveCount(5)
  await expect(editor.locator('[id^="editor-toc"], [data-toc-id]')).toHaveCount(0)
  expect(errors).toEqual([])
})

for (const width of [390, 320]) test(`small screens expose a collapsible directory in ordinary and fullscreen at ${width}px`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 844 })
  const { editor, toc, errors } = await open(page)
  const toggle = toc.getByRole('button', { name: /目录/ })
  for (const fullscreen of [false, true]) {
    if (fullscreen) await page.locator('.toolbar [data-menu-key="fullScreen"]').click()
    await expect(toggle).toBeVisible()
    await expect(toc.locator('.toc-panel')).toBeHidden()
    await toggle.click()
    await expect(toggle).toHaveAttribute('aria-expanded', 'true')
    await toc.getByRole('button', { name: '具体步骤', exact: true }).click()
    await expect(editor.getByRole('heading', { name: '具体步骤', exact: true })).toBeInViewport()
    await expect(toggle).toBeInViewport()
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    // The first Escape closes the directory; fullscreen stays open.
    await toggle.click(); await page.keyboard.press('Escape')
    await expect(toggle).toHaveAttribute('aria-expanded', 'false')
    if (fullscreen) await expect(page.getByRole('dialog', { name: '全屏编辑正文', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width)
    await page.screenshot({ path: info.outputPath(`editor-directory-${width}-${fullscreen}.png`), animations: 'disabled' })
  }
  expect(errors).toEqual([])
})

test('directory adapts alongside the AI panel and survives fullscreen transitions', async ({ page }) => {
  await page.setViewportSize({ width: 2540, height: 1000 })
  const { editor, toc, errors } = await open(page)
  await page.getByRole('button', { name: '问 AI', exact: true }).click()
  await expect(toc.locator('.toc-toggle')).toBeHidden()
  await page.locator('.toolbar [data-menu-key="fullScreen"]').click()
  await expect(toc.locator('.toc-toggle')).toBeHidden()
  const body = await editor.boundingBox(), panel = await page.locator('#writing-ai-panel').boundingBox()
  expect(body!.x + body!.width).toBeLessThan(panel!.x)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await expect(toc.locator('.toc-toggle')).toBeVisible()
  await toc.locator('.toc-toggle').click()
  await toc.getByRole('button', { name: '完成检查', exact: true }).click()
  await expect(editor.getByRole('heading', { name: '完成检查', exact: true })).toBeInViewport()
  await page.getByRole('button', { name: /退出全屏/ }).click()
  await expect(toc.locator('.toc-toggle')).toBeVisible()
  await page.getByRole('button', { name: '收起 AI 写作助手' }).click()
  await expect(toc.locator('.toc-toggle')).toBeHidden()
  expect(errors).toEqual([])
})
