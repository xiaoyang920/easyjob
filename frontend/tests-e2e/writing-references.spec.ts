test('quoted ranges are fully underlined across wrapped lines, follow edits, and stay out of saved HTML', async ({ page }, info) => {
  const { panel, input, errors } = await fixture(page, false, false)
  const text = '这是一段需要完整引用和分析的文字，跨行以后也应当显示提示线。'.repeat(6)
  await page.route('**/api/article/42/edit', route => route.fulfill({ json: { code: 200, data: { articleId: '42', title: '引用下划线', content: `<p>前面的段落。</p><p>${text}</p>`, summary: '', status: 0, revisionId: 'qa', lockVersion: 1 } } }))
  await page.reload()
  const editor = page.locator('[data-slate-editor]')
  await expect(editor).toContainText(text)
  // WangEditor removes its initial data-slate-inline="false" bookkeeping on first render.
  const documentHtml = async () => (await editor.innerHTML()).replace(/ data-slate-inline="false"/g, '')
  const before = await documentHtml()
  await quoteParagraph(page, 1)
  const lines = page.locator('.writing-reference-lines span')
  await expect.poll(() => lines.count()).toBeGreaterThan(2)
  const originalId = await lines.first().getAttribute('data-reference-id')
  const checkGeometry = async () => {
    const rects = await editor.locator('p').nth(1).locator('[data-slate-string]').evaluate(el => {
      const range = document.createRange(); range.selectNodeContents(el)
      return [...range.getClientRects()].map(r => ({ left: r.left, right: r.right, bottom: r.bottom }))
    })
    for (const rect of rects) {
      expect(await lines.evaluateAll((elements, target) => elements.some(el => {
        const actual = el.getBoundingClientRect()
        return Math.abs(actual.left - target.left) < 2 && Math.abs(actual.right - target.right) < 2 && Math.abs(actual.top - target.bottom + 1) < 2
      }), rect)).toBe(true)
    }
  }
  await checkGeometry()
  expect(await documentHtml()).toBe(before)
  await quoteParagraph(page, 0)
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(2)
  await panel.getByRole('button', { name: '移除引用 2', exact: true }).click()
  await expect.poll(async () => new Set(await lines.evaluateAll(nodes => nodes.map(node => node.getAttribute('data-reference-id')))).size).toBe(1)
  await expect(lines.first()).toHaveAttribute('data-reference-id', originalId!)
  await editor.locator('p').first().click()
  await page.keyboard.press('Home')
  await page.keyboard.insertText('新增的其他内容。')
  await expect(editor).toContainText('新增的其他内容。')
  await checkGeometry()
  await page.screenshot({ path: info.outputPath('quoted-text-underlines.png'), animations: 'disabled' })
  await input.fill('解释这段文字')
  await panel.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect(panel.locator('.sent-writing-reference')).toHaveCount(1)
  await expect.poll(() => lines.count()).toBeGreaterThan(2)
  await panel.getByRole('button', { name: '新话题', exact: true }).click()
  await expect(lines).toHaveCount(0)
  expect(errors).toEqual([])
})

test('two separate selections accumulate, remove independently, send in order and restore from history', async ({ page }, info) => {
  const { sent, errors, panel, input } = await fixture(page, false, false)
  await page.locator('.w-e-hover-bar [data-menu-key="articleAiReference"]').click()
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(1)
  await input.fill('比较这两个地方')
  await quoteParagraph(page, 0)
  let cards = panel.locator('.pending-writing-reference')
  await expect(cards).toHaveCount(2)
  await cards.nth(0).getByLabel('查看引用：选中文字 1').click()
  await cards.nth(1).getByLabel('查看引用：选中文字 2').click()
  await expect(cards.nth(0).locator('pre')).toHaveText('需要讨论的选中文字。')
  await expect(cards.nth(1).locator('pre')).toHaveText('第一段不参与引用。')
  await page.screenshot({ path: info.outputPath('multiple-writing-references.png'), animations: 'disabled' })
  await cards.nth(0).getByRole('button', { name: '移除引用 1', exact: true }).click()
  await expect(cards).toHaveCount(1)
  await expect(cards.first()).toContainText('第一段不参与引用。')
  await expect(input).toHaveValue('比较这两个地方')
  await quoteParagraph(page, 1)
  await expect(cards).toHaveCount(2)
  expect(sent).toEqual([])
  await panel.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect.poll(() => sent.length).toBe(1)
  const decoded = readWritingMessage(sent[0].message)
  expect(decoded.content).toBe('比较这两个地方')
  expect(decoded.references?.map(ref => ref.text)).toEqual(['第一段不参与引用。', '需要讨论的选中文字。'])
  expect(sent[0].editorContext.selection).toBe('')
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(0)
  await expect(panel.locator('.sent-writing-reference')).toHaveCount(2)
  await expect(input).toBeEnabled()
  await input.fill('再解释一下')
  await panel.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect.poll(() => sent.length).toBe(2)
  expect(sent[1].message).toBe('再解释一下')
  await expect(input).toBeEnabled()
  await page.goto('/ai-chat?conversationId=101')
  await expect(page.locator('.sent-writing-reference')).toHaveCount(2)
  await page.getByLabel('查看引用：选中文字 1').click()
  await page.getByLabel('查看引用：选中文字 2').click()
  await expect(page.locator('.sent-writing-reference').nth(0).locator('pre')).toHaveText('第一段不参与引用。')
  await expect(page.locator('.sent-writing-reference').nth(1).locator('pre')).toHaveText('需要讨论的选中文字。')
  expect(errors).toEqual([])
})

test('reference count limit preserves existing quotes and removing one frees a slot', async ({ page }) => {
  const { sent, errors, panel, input } = await fixture(page)
  for (let index = 0; index < 5; index += 1) {
    await quoteParagraph(page, index % 2)
    await expect(panel.locator('.pending-writing-reference')).toHaveCount(index + 1)
  }
  await quoteParagraph(page, 1)
  await expect(page.getByText('本次最多引用 5 处，请先移除不需要的引用', { exact: true })).toBeVisible()
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(5)
  await panel.getByRole('button', { name: '移除引用 3', exact: true }).click()
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(4)
  await quoteParagraph(page, 1)
  await expect(panel.locator('.pending-writing-reference')).toHaveCount(5)
  await expect(input).toBeInViewport()
  expect(sent).toEqual([])
  expect(errors).toEqual([])
})

