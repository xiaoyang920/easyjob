import { test, expect, type Page } from '@playwright/test'
import { readWritingMessage } from '../src/utils/writingReferences'

test.use({ actionTimeout: 8000 })
async function fixture(page: Page, conflict = false, open = true) {
  await page.setViewportSize({ width: 1440, height: 900 })
  const sent: any[] = [], errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    localStorage.setItem('token', `qa.${btoa(JSON.stringify({ sub: '7', exp: Math.floor(Date.now() / 1000) + 3600 }))}.references`)
    localStorage.setItem('userId', '7')
  })
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname
    if (path.endsWith('/agent/chat/stream')) {
      sent.push(route.request().postDataJSON())
      if (conflict && sent.length > 1) return route.fulfill({ status: 409, json: { code: 409, message: '会话正在运行' } })
      const events = ['__CONV_ID__:101', '__RUN_ID__:reference-run', '__REPLY__:{"content":"这是引用内容的说明。"}', '[DONE]']
      return route.fulfill({ contentType: 'text/event-stream', body: events.map(data => `data:${data}\n\n`).join('') })
    }
    let data: any = []
    if (path.endsWith('/article/42/edit')) data = { articleId: '42', title: '引用验收文章', summary: '摘要内容',
      content: '<p>第一段不参与引用。</p><p>需要讨论的选中文字。</p>', status: 0, revisionId: 'quote-qa', lockVersion: 1 }
    else if (path.endsWith('/user/space/7')) data = { userId: '7', role: 0, status: 1 }
    else if (path.endsWith('/run')) data = null
    else if (path.endsWith('/messages')) data = sent.length ? [{ messageId: '1001', role: 'user', content: sent[0].message }, { messageId: '1002', role: 'assistant', content: '这是引用内容的说明。' }] : []
    else if (path.endsWith('/agent/run-overview')) data = { items: [] }
    else if (path.endsWith('/unread-count') || path.endsWith('/total-unread-count')) data = 0
    await route.fulfill({ json: { code: 200, data } })
  })
  await page.goto('/create-article?id=42')
  const editor = page.locator('[data-slate-editor]')
  await expect(editor).toContainText('需要讨论的选中文字。')
  await editor.locator('p').nth(1).locator('[data-slate-string]').evaluate(el => {
    const range = document.createRange(); range.selectNodeContents(el)
    const selection = getSelection()!; selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  })
  await expect(page.locator('.w-e-hover-bar')).toBeVisible()
  if (open) await page.getByRole('button', { name: '问 AI', exact: true }).click()
  return { sent, errors, panel: page.locator('#writing-ai-panel'), input: page.getByRole('textbox', { name: '消息内容' }) }
}

