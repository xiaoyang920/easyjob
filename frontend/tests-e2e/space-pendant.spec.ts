import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

// This scenario actually publishes a product and debits a fixture wallet.
const fixtureFile = process.env.EASYJOB_PENDANT_BROWSER_FIXTURE
test.skip(!fixtureFile, 'Requires an explicitly selected disposable platform fixture and a funded reader.')

test('publishes an original pendant, buys it, and renders it for anonymous visitors after delisting', async ({ page, browser, baseURL }) => {
  page.setDefaultTimeout(7500)
  const fixture = JSON.parse(readFileSync(fixtureFile!, 'utf8'))
  async function login(target: Page, key: string) {
    const account = fixture.users.find((user: { key: string }) => user.key === key)
    const response = await target.request.post('/api/auth/login', { data: { email: account.email, password: fixture.password } })
    const body = await response.json()
    expect(body.code).toBe(200)
    await target.addInitScript(identity => {
      localStorage.setItem('token', identity.token)
      localStorage.setItem('userId', String(identity.userId))
    }, body.data)
    return String(body.data.userId)
  }

  await login(page, 'admin')
  await page.goto('/admin?section=spaceProducts')
  await page.getByRole('button', { name: '上传作品' }).click()
  const template = await page.getByRole('link', { name: /对位模板/ }).getAttribute('href')
  expect(decodeURIComponent(template!)).toContain('r="153.6"')
  const png = readFileSync(new URL('../../docs/assets/examples/kingfisher-pendant.png', import.meta.url))
  const title = '挂件验收-' + Date.now()
  await page.getByLabel('作品名称').fill(title)
  await page.getByLabel('作者署名').fill('验收画师')
  await page.getByRole('group', { name: '挂件原稿' }).locator('input[type=file]').setInputFiles({ name: 'kingfisher-pendant.png', mimeType: 'image/png', buffer: png })
  const preview = page.locator('.pendant-preview')
  await expect(preview.locator('.pendant-art')).toBeVisible()
  await expect(preview.locator('.sample-profile strong')).toBeVisible()
  await expect(preview.locator('.space-banner')).toBeVisible()
  const day = await preview.evaluate(el => getComputedStyle(el).backgroundColor)
  await page.getByLabel('背景', { exact: true }).selectOption('night')
  expect(await preview.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(day)
  await page.getByLabel('头像尺寸').selectOption('80')
  await expect(preview.locator('.portrait')).toHaveCSS('width', '80px')
  expect((await preview.locator('.pendant-art').boundingBox())!.width).toBeGreaterThan(80)
  await page.getByRole('button', { name: '保存作品' }).click()
  await page.getByLabel('硬币价格').fill('1')
  await page.getByRole('button', { name: '上架商品' }).click()
  await expect(page.getByText('商品已上架', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: '作品库' }).click()
  const artwork = page.locator('.component-row').filter({ hasText: title })
  await artwork.getByRole('button', { name: '编辑作品信息' }).click()
  await page.getByLabel('作者署名').fill('更正后的署名')
  await page.getByRole('button', { name: '保存作品信息' }).click()
  await expect(artwork).toContainText('更正后的署名')
  await page.getByRole('button', { name: '商品列表' }).click()

  const buyer = await browser.newContext({ baseURL })
  const visitor = await browser.newContext({ baseURL })
  try {
    const fitting = await buyer.newPage()
    const owner = await login(fitting, 'reader')
    await fitting.goto('/growth-shop?tab=skins')
    const card = fitting.locator('.skin-product').filter({ hasText: title })
    await expect(card).toContainText('更正后的署名')
    await fitting.getByRole('button', { name: '头像挂件', exact: true }).click()
    await card.getByRole('button', { name: '购买', exact: true }).click()
    await fitting.getByRole('button', { name: '确定', exact: true }).click()
    await card.getByRole('button', { name: '使用', exact: true }).click()
    await expect(card.getByRole('button', { name: '使用中' })).toBeDisabled()
    await fitting.goto('/space-customization')
    const wardrobe = fitting.locator('.customization-options section')
      .filter({ has: fitting.getByRole('heading', { name: '头像挂件', exact: true }) })
    await wardrobe.getByRole('button', { name: '取消使用' }).click()
    await expect(fitting.locator('.preview-avatar .pendant-art')).toHaveCount(0)
    await wardrobe.getByRole('button', { name: new RegExp(title) }).click()
    await wardrobe.getByRole('button', { name: '使用', exact: true }).click()
    await expect(fitting.getByText('已使用头像挂件', { exact: true })).toBeVisible()

    const row = page.locator('.product-row').filter({ hasText: title })
    await row.getByLabel('状态').selectOption({ label: '已下架' })
    await row.getByRole('button', { name: '保存修改' }).click()
    await expect(page.getByText('商品已更新', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '作品库' }).click()
    await artwork.getByRole('button', { name: '撤回作品' }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(page.locator('.product-error')).toContainText('已出售')
    await page.getByRole('button', { name: '上传作品' }).click()
    const draftName = '草稿-' + title
    await page.getByLabel('作品名称').fill(draftName)
    await page.getByLabel('作者署名').fill('验收画师')
    await page.getByRole('group', { name: '挂件原稿' }).locator('input[type=file]').setInputFiles({ name: 'draft.png', mimeType: 'image/png', buffer: png })
    await page.getByRole('button', { name: '保存作品' }).click()
    await expect(page.getByText('作品已保存，填写价格即可上架')).toBeVisible()
    await page.getByRole('button', { name: '作品库' }).click()
    const draft = page.locator('.component-row').filter({ hasText: draftName })
    await draft.getByRole('button', { name: '撤回作品' }).click()
    await page.getByRole('button', { name: '确定', exact: true }).click()
    await expect(draft).toHaveCount(0)
    const publicPage = await visitor.newPage()
    await publicPage.goto('/user-space/' + owner)
    const portrait = publicPage.locator('.user-avatar')
    const art = portrait.locator('.pendant-art')
    await expect(art).toHaveJSProperty('naturalWidth', 512)
    await expect(art).toHaveCSS('pointer-events', 'none')
    await expect(portrait).toHaveCSS('border-top-width', '0px')
    await expect(portrait.locator('.space-avatar-crest')).toHaveCount(0)
    for (const [viewport, diameter] of [[1360, 120], [620, 80], [390, 70]]) {
      await publicPage.setViewportSize({ width: viewport, height: 850 })
      await expect(portrait).toHaveCSS('width', diameter + 'px')
      await expect(portrait.locator('.portrait')).toHaveCSS('width', diameter + 'px')
      expect((await art.boundingBox())!.width).toBeGreaterThan(diameter)
    }
  } finally {
    await visitor.close()
    await buyer.close()
  }
})
