test('new unsaved articles can chat through the existing stream and hiding the drawer keeps the same request/conversation', async ({ page }) => {
  const { errors } = await fixture(page, { fresh: true })
  let release!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const messages: any[] = []
  await page.route('**/api/agent/chat/stream', async route => {
    messages.push(route.request().postDataJSON())
    if (messages.length === 1) await gate
    const events = ['__CONV_ID__:101', '__RUN_ID__:writing-run', '__ANSWER__:{"type":"start","mode":"direct"}', '__ANSWER__:{"type":"delta","seq":0,"content":"可以从一个具体的故事开篇。"}', '__ANSWER__:{"type":"complete","seq":1}', '[DONE]']
    await route.fulfill({ contentType: 'text/event-stream', body: events.map(data => `data:${data}\n\n`).join('') })
  })
  await page.getByRole('button', { name: '问 AI', exact: true }).click()
  const panel = page.locator('#writing-ai-panel')
  const input = panel.getByRole('textbox', { name: '消息内容' })
  await input.fill('怎么开篇更自然？')
  await panel.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect.poll(() => messages.length).toBe(1)
  await panel.getByRole('button', { name: '收起 AI 写作助手' }).click()
  release()
  await page.getByRole('button', { name: '问 AI', exact: true }).click()
  await expect(panel.locator('.message-bubble').last()).toContainText('可以从一个具体的故事开篇。')
  await expect(input).toBeEnabled()
  await input.fill('再给一个例子')
  await panel.getByRole('button', { name: '发送消息', exact: true }).click()
  await expect.poll(() => messages.length).toBe(2)
  expect(messages[0].conversationId).toBeNull()
  expect(messages[1].conversationId).toBe('101')
  expect(messages.every(message => !message.originArticleId)).toBe(true)
  expect(await page.evaluate(() => localStorage.getItem('ai_conversation_id:7'))).toBe('unrelated-chat')
  await expect(page.locator('.title-input')).toHaveValue('')
  expect(errors).toEqual([])
})

