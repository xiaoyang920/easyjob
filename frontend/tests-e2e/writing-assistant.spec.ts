import { test, expect, type Page } from '@playwright/test'

test.use({ actionTimeout: 8000 })
const articleHtml = '<p>这是尚未发布的草稿正文。</p><p>保留原意，讲清楚一个想法。</p>'
async function fixture(page: Page, options: { fresh?: boolean; long?: boolean; edit?: boolean } = {}) {
  const requests: { path: string; query: string; method: string; body: any }[] = []
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => {
    localStorage.setItem('token', `qa.${btoa(JSON.stringify({ sub: '7', exp: Math.floor(Date.now() / 1000) + 3600 }))}.writing`)
    localStorage.setItem('userId', '7')
    localStorage.setItem('ai_conversation_id:7', 'unrelated-chat')
  })
  await page.route('**/api/**', async route => {
    const url = new URL(route.request().url()), path = url.pathname
    requests.push({ path, query: url.searchParams.toString(), method: route.request().method(), body: route.request().postDataJSON() })
    let data: any = []
    if (path.endsWith('/article/42/edit')) data = { articleId: '42', title: '正在写的文章', summary: '当前摘要', content: options.long ? `<p>${'这是很长的草稿。'.repeat(2200)}</p>` : articleHtml, status: 0, revisionId: 'qa-revision', lockVersion: 1 }
    else if (path.endsWith('/user/space/7')) data = { userId: '7', nickName: '写作验收', role: 0, status: 1 }
    else if (path.endsWith('/category/list')) data = [{ categoryId: '1', categoryName: '技术' }]
    else if (path.endsWith('/comment/list') || path.endsWith('/comment/quotes') || path.endsWith('/comment/quote-markers')) data = { records: [], total: 0, pages: 1, nextCursor: '' }
    else if (path.startsWith('/api/reading/')) data = { sessionId: 'qa-reading', sessionToken: 'qa-reading', level: 0, totalSeconds: 0, nextLevel: 1, secondsToNext: 1800, rules: [{ level: 0, minSeconds: 0 }, { level: 1, minSeconds: 1800 }] }
    else if (path.endsWith('/unread-count') || path.endsWith('/total-unread-count')) data = 0
    else if (path.endsWith('/agent/run-overview')) data = { items: [] }
    await route.fulfill({ json: { code: 200, data } })
  })
  await page.goto(options.fresh ? '/create-article' : options.edit ? '/edit-article?id=42' : '/create-article?id=42')
  await expect(page.locator('[data-slate-editor]')).toBeVisible()
  if (!options.fresh) await expect(page.locator('[data-slate-editor]')).toContainText(options.long ? '这是很长的草稿。' : '尚未发布')
  return { requests, errors }
}

