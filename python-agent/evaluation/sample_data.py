def generate(output: Path):
    output.mkdir(parents=True, exist_ok=True)
    articles, cases = [], []
    for number, (title, sections, queries, reference, related) in enumerate(DOCUMENTS, 1):
        sid = f"sample_{number:02}"
        body = '<p>合成 RAG 评测样例；用于检索测试，不代表真实用户文章。</p>'
        body += ''.join(f'<h2>{html.escape(heading)}</h2><p>{html.escape(text)}</p>' for heading, text in sections)
        if reference:
            body += f'<p>参考文档：<a href="{html.escape(reference, quote=True)}">官方文档</a></p>'
        articles.append({'id': sid, 'title': '[评测样例] ' + title, 'content': body,
                         'summary': sections[0][1], 'content_type': 1, 'source': 'synthetic_authored'})
        for index, query in enumerate(queries, 1):
            relevance = {sid: 3, **{f'sample_{key:02}': grade for key, grade in related.items()}}
            cases.append({'id': f'rag_sample_{number:02}_{index}', 'kind': 'rag', 'query': query,
                          'reviewed': True, 'annotation_source': 'synthetic_authored', 'relevance': relevance,
                          'label_basis': [{'document': sid, 'reason': '目标文章的章节直接覆盖问题，见正文；其他标记为辅助语境。'}],
                          'category': '术语问题' if index == 1 else '场景改述'})
    ids = {a['id'] for a in articles}
    assert all(set(c['relevance']) <= ids for c in cases)
    for name, rows in [('rag.samples.articles.jsonl', articles), ('rag.samples.cases.jsonl', cases)]:
        (output / name).write_text(''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in rows), encoding='utf-8')
    print(f'Generated {len(articles)} synthetic articles and {len(cases)} labelled questions.')


if __name__ == '__main__':
    generate(Path(__file__).resolve().parent / 'datasets')
