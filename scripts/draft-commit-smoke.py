"""Local temporary fixtures: real approval permission, Java transaction and receipt reconciliation."""
import asyncio
import json
import sys
from pathlib import Path
from types import SimpleNamespace
from uuid import uuid4
from fastapi import HTTPException
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'python-agent'))
from app.clients.mysql_client import db
from app.config import settings
from app.services import draft_commit
from app.services.draft_gateway import draft_hash
from app.services.conversation import ConversationService
from app.services.run_repository import RunRepository
from app.rpc import blog_client
from app.rpc.discovery import catalog
from app.utils.snowflake import snowflake

async def main():
    assert settings.MYSQL_HOST in ('localhost','127.0.0.1','::1'),'Only local fixture databases are allowed'
    await db.connect();cid=None;aid=snowflake.next_id();rid=str(uuid4());token=str(uuid4())
    uid=await db.fetch_val('SELECT user_id FROM user_info WHERE status=1 ORDER BY user_id LIMIT 1')
    assert uid
    result={}
    try:
        cid=await ConversationService().create_conversation(uid)
        draft=SimpleNamespace(title='服务拆分临时测试草稿',summary='仅供本机测试，结束后清理。',content='测试正文')
        html='<p>测试正文</p>';content_hash=draft_hash(draft,html)
        await db.execute("""INSERT INTO agent_run(run_id,conversation_id,user_id,request_id,input_hash,execution_token,status,
            deadline,draft_hash,result_json,data_source) VALUES(:rid,:cid,:uid,:rid,:hash,:token,'running',
            TIMESTAMPADD(MINUTE,5,UTC_TIMESTAMP(6)),:hash,'{}','evaluation')""",
            {'rid':rid,'cid':cid,'uid':uid,'hash':content_hash,'token':token})
        body={'articleId':str(aid),'runId':rid,'executionToken':token,'title':draft.title,'summary':draft.summary,
            'markdown':draft.content,'html':html,'draftHash':content_hash,'baseDraftHash':content_hash}
        state={'run_id':rid,'user_id':uid,'conversation_id':cid,'execution_token':token}
        try:
            await blog_client.save_draft(uid,body)
            raise AssertionError('unsigned save accepted')
        except blog_client.ServiceError as exc:assert exc.status==409
        result['unsigned_save_rejected']=True
        body['savePermit']=await draft_commit.reserve(state,body)
        assert (await RunRepository().cancel(cid,uid))['status']=='saving'
        result['cancel_after_reservation_returns_saving']=True
        saved=await blog_client.save_draft(uid,body)
        assert int(saved['articleId'])==aid
        assert await db.fetch_val('SELECT COUNT(*) FROM article_info WHERE article_id=:aid',{'aid':aid})==0
        assert await db.fetch_val('SELECT COUNT(*) FROM article_revision WHERE article_id=:aid AND author_id=:uid',{'aid':aid,'uid':uid})==1
        result['draft_only_in_revision']=True
        assert await blog_client.save_draft(uid,{**body,'savePermit':'expired-or-lost'})==saved
        assert await db.fetch_val('SELECT COUNT(*) FROM article_revision WHERE article_id=:aid',{'aid':aid})==1
        result['repeat_save_idempotent']=True
        receipt=await blog_client.draft_receipt(uid,rid)
        assert receipt=={'articleId':str(aid),'draftHash':content_hash}
        # Simulate response loss: Java committed, Agent has not updated its run yet.
        await draft_commit.complete(uid,rid,receipt)
        assert await db.fetch_val('SELECT draft_article_id FROM agent_run WHERE run_id=:rid',{'rid':rid})==aid
        result['lost_response_reconciled_by_receipt']=True
        assert await blog_client.draft_receipt(uid+1,rid) is None
        result['receipt_owner_isolated']=True
        print(json.dumps(result,ensure_ascii=False,indent=2))
        (ROOT/'logs/draft-commit-live.json').write_text(json.dumps(result,indent=2),encoding='utf-8')
    finally:
        # Only IDs generated by this invocation are removed; existing user data is untouched.
        async with db.transaction():
            await db.execute('DELETE FROM article_review_log WHERE article_id=:aid AND actor_id=:uid',{'aid':aid,'uid':uid})
            await db.execute('DELETE FROM article_revision WHERE article_id=:aid AND author_id=:uid',{'aid':aid,'uid':uid})
            await db.execute('DELETE FROM article_agent_save_receipt WHERE run_id=:rid AND user_id=:uid',{'rid':rid,'uid':uid})
            await db.execute('DELETE FROM agent_run WHERE run_id=:rid AND user_id=:uid',{'rid':rid,'uid':uid})
            if cid:await db.execute('DELETE FROM ai_conversation WHERE conversation_id=:cid AND user_id=:uid',{'cid':cid,'uid':uid})
        await blog_client.close_client();await catalog.close();await db.disconnect()

if __name__=='__main__':asyncio.run(main())
